#!/bin/bash -e

green='\033[0;32m'
red='\033[0;31m'
nocolor='\033[0m'

PACKAGE_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$PACKAGE_DIR")"
WORKDIR="$PACKAGE_DIR/workdir"
SHADER_DIR="$PACKAGE_DIR/shaders"
OUTPUT="$WORKDIR/bench-vulkan"

echo -e "${green}=== Vulkan GPU Benchmark Builder ===${nocolor}"

NDK_CLANG="${NDK_CLANG:-$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin}"
SDK_VER="${BENCH_SDK_VER:-35}"
TARGET_TRIPLE="aarch64-linux-android${SDK_VER}"

if [ ! -x "$NDK_CLANG/${TARGET_TRIPLE}-clang" ]; then
    echo -e "${red}NDK cross-compiler not found at $NDK_CLANG/${TARGET_TRIPLE}-clang${nocolor}"
    echo "  Set NDK or NDK_CLANG to the NDK toolchain path"
    exit 1
fi

NDK_SYSROOT="$NDK/toolchains/llvm/prebuilt/linux-x86_64/sysroot"

mkdir -p "$WORKDIR"

echo "Compiling shaders to SPIR-V..."

glslangValidator -V "$SHADER_DIR/compute.comp" -o "$WORKDIR/compute.spv" --target-env vulkan1.3
glslangValidator -V "$SHADER_DIR/fp16_compute.comp" -o "$WORKDIR/fp16_compute.spv" --target-env vulkan1.3
glslangValidator -V "$SHADER_DIR/vert.vert" -o "$WORKDIR/vert.spv" --target-env vulkan1.3
glslangValidator -V "$SHADER_DIR/frag.frag" -o "$WORKDIR/frag.spv" --target-env vulkan1.3

echo "Generating SPIR-V header..."
python3 -c "
import sys, os
workdir = sys.argv[1]
shaders = ['compute', 'fp16_compute', 'vert', 'frag']
lines = []
lines.append('/* Auto-generated by build.sh - do not edit */')
lines.append('#ifndef BENCH_SHADERS_H')
lines.append('#define BENCH_SHADERS_H')
lines.append('#include <stdint.h>')
lines.append('#include <stddef.h>')
for s in shaders:
    with open(f'{workdir}/{s}.spv', 'rb') as f:
        data = f.read()
    lines.append('')
    lines.append(f'static const unsigned char {s}_spv_data[] = {{')
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        hex_bytes = ', '.join(f'0x{b:02x}' for b in chunk)
        lines.append(f'    {hex_bytes},')
    lines.append('};')
    lines.append(f'static const unsigned int {s}_spv_len = {len(data)};')
lines.append('')
lines.append('#endif')
with open(f'{workdir}/shaders.h', 'w') as f:
    f.write('\n'.join(lines) + '\n')
" "$WORKDIR"

echo "Compiling benchmark binary..."

"$NDK_CLANG/${TARGET_TRIPLE}-clang" \
    --sysroot="$NDK_SYSROOT" \
    -std=c11 \
    -Wall -Wextra \
    -O2 -flto \
    -DANDROID \
    -DTARGET_API="$SDK_VER" \
    -I"$WORKDIR" \
    -I"$NDK_SYSROOT/usr/include" \
    -o "$OUTPUT" \
    "$PACKAGE_DIR/main.c" \
    -L"$NDK_SYSROOT/usr/lib/aarch64-linux-android/$SDK_VER" \
    -lvulkan -lm

"$NDK_CLANG/llvm-strip" "$OUTPUT"

echo -e "${green}Benchmark built: $OUTPUT${nocolor}"
ls -lh "$OUTPUT"

echo ""
echo "Termux usage:"
echo "  adb push $OUTPUT /data/data/com.termux/files/home/"
echo "  adb shell chmod +x /data/data/com.termux/files/home/bench-vulkan"
echo "  adb shell /data/data/com.termux/files/home/bench-vulkan"
